const translations: Record<Lang, Dict> = { ko, en, ja, zh, vi };

function resolve(dict: Dict, path: string): any {
  const parts = path.split(".");
  let cur: any = dict;
  for (const p of parts) {
    if (cur == null) return path;
    cur = cur[p];
  }
  return cur === undefined ? path : cur;
}

interface LangContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => any;
}

const LanguageContext = createContext<LangContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "en";
    const saved = window.localStorage.getItem("dostac-lang-v2") as Lang | null;
    return saved && (["ko", "en", "ja", "zh", "vi"] as Lang[]).includes(saved) ? saved : "en";
  });

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
    }
    if (typeof window !== "undefined") {
      window.localStorage.setItem("dostac-lang-v2", lang);
    }
  }, [lang]);

  const setLang = (l: Lang) => setLangState(l);
  const t = (key: string) => resolve(translations[lang], key);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useT(): LangContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      lang: "en",
      setLang: () => {},
      t: (key: string) => resolve(translations.en, key),
    };
  }
  return ctx;
}


export function useLang(): { lang: Lang; setLang: (l: Lang) => void } {
  const { lang, setLang } = useT();
  return { lang, setLang };
}

